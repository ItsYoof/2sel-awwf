import json

lines = text.strip().split('\n')
questions = []

# First special question
q1 = lines[0].strip()
a1 = lines[1].strip()
questions.append({
    "questionText": q1,
    "media": "",
    "answer": a1
})

# Letter questions
for line in lines[2:]:
    line = line.strip()
    if not line or "أسئلة حرف" in line:
        continue
    
    if " - سؤال: " in line and " - جواب: " in line:
        parts = line.split(" - سؤال: ")
        prefix = parts[0].strip()
        rest = parts[1].split(" - جواب: ")
        question_text = rest[0].strip()
        answer_text = rest[1].strip()
        
        full_question = f"{prefix} - {question_text}"
        questions.append({
            "questionText": full_question,
            "media": "",
            "answer": answer_text
        })

# Output as JS objects
for q in questions:
    print("    {")
    print(f"        questionText: {json.dumps(q['questionText'], ensure_ascii=False)},")
